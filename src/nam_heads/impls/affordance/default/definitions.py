# Merge in auto-classified categories from WordNet hypernym chains.
# verb_categories.json maps verb -> category for canonical forms not in
# the hand-curated seed above.  Generated by build_synonyms.py.
_CATEGORY_PATH = os.path.join(os.path.dirname(__file__), "data", "verb_categories.json")

def _merge_generated_categories() -> None:
    """Load verb_categories.json and merge entries into VERB_CATEGORIES."""
    try:
        with open(_CATEGORY_PATH) as f:
            generated = json.load(f)
    except FileNotFoundError:
        return
    for verb, cat in generated.items():
        if cat in VERB_CATEGORIES:
            VERB_CATEGORIES[cat].add(verb)

_merge_generated_categories()

