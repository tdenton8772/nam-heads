"""BFO/CCO class registry, extended by the selected ontology implementation.

Loads ``classes.json`` (every class of the HermiT-certified BFO 2020 + CCO
v2.2 TBox, generated by ``generate.py`` from the pinned releases) and answers:
is this a class, what is it called, what are its ancestors, does it subsume
that one, are two classes disjoint, which BFO branch is it in, and which
single class does a set of evidence settle on.

An ontology implementation may bring its own classes (IMPL_META "ontology":
an extension artifact, schema EXTENSION_SCHEMA). While the head-slot manifest
selects that implementation, every process that reads the manifest calls
``use_extension`` (``src/encoders/slots.py`` ``apply_ontology``), and
``get_registry()`` answers for BFO/CCO plus the extension's classes:

- an extension only ADDS classes. It cannot redefine a BFO/CCO class (by
  CURIE or by IRI), so every BFO/CCO answer (is_class, ancestors, labels,
  nearest_key over BFO/CCO keys, disjointness, sources) is the same with or
  without it;
- an extension class's parents may be BFO/CCO classes, so it backs off to
  them, has a BFO branch, and resolves to the nearest BFO/CCO key in the
  heads' tables;
- with no extension selected, ``get_registry()`` is the built-in registry.
"""

import json
import logging
import re
import threading
from functools import lru_cache
from pathlib import Path
from typing import Dict, FrozenSet, Iterable, List, Optional, Tuple

from . import bindings as B

logger = logging.getLogger(__name__)

CLASSES_PATH = Path(__file__).parent / "classes.json"
EXTENSION_SCHEMA = "nam-ontology-extension/1"
_EXTENSION_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{1,31}$")

# BFO's top-level partition of `entity`, used to group classes into tiers.
# Order is the planner's default tier order.
BRANCHES: Tuple[str, ...] = (
    B.INDEPENDENT_CONTINUANT,
    B.OCCURRENT,
    B.SPECIFICALLY_DEPENDENT_CONTINUANT,
    B.GENERICALLY_DEPENDENT_CONTINUANT,
)


class OntologyRegistry:
    def __init__(self, doc: dict, extension: Optional[dict] = None):
        self.sources = doc.get("sources", {})
        # The active extension: {"name", "classes" (its own CURIEs),
        # "emittable", "prefixes", "source"}; None for the built-in registry.
        self.extension = extension
        self._classes: Dict[str, dict] = doc["classes"]
        for c, v in self._classes.items():
            for p in v["parents"]:
                if p not in self._classes:
                    raise ValueError(f"{c}: parent {p} missing from classes.json")
        missing = sorted(b for b in B.named_classes() if b not in self._classes)
        if missing:
            raise ValueError(f"bindings name classes absent from classes.json: {missing}"
                             " -- rerun `python -m nam_heads.ontology.generate`")
        self._ancestors: Dict[str, FrozenSet[str]] = {}
        for c in self._classes:
            self._ancestors[c] = self._walk_up(c)
        self._disjoint: List[FrozenSet[str]] = [frozenset(d) for d in doc.get("disjoint", [])]

    # ---- lookups ----------------------------------------------------------
    def is_class(self, c: str) -> bool:
        return c in self._classes

    def classes(self) -> List[str]:
        return list(self._classes)

    def label(self, c: str) -> str:
        v = self._classes.get(c)
        return v["label"] if v else c

    def iri(self, c: str) -> str:
        return self._classes[c]["iri"]

    def definition(self, c: str) -> str:
        return self._classes[c]["definition"]

    def parents(self, c: str) -> List[str]:
        return list(self._classes[c]["parents"])

    # ---- hierarchy --------------------------------------------------------
    def _walk_up(self, c: str) -> FrozenSet[str]:
        seen, todo = set(), list(self._classes[c]["parents"])
        while todo:
            p = todo.pop()
            if p not in seen:
                seen.add(p)
                todo.extend(self._classes[p]["parents"])
        return frozenset(seen)

    def ancestors(self, c: str, inclusive: bool = False) -> FrozenSet[str]:
        a = self._ancestors[c]
        return a | {c} if inclusive else a

    def is_a(self, c: str, d: str) -> bool:
        """True if every instance of c is an instance of d (c == d counts)."""
        return c == d or d in self._ancestors[c]

    def descendants(self, c: str, inclusive: bool = False) -> FrozenSet[str]:
        out = {x for x in self._classes if c in self._ancestors[x]}
        if inclusive:
            out.add(c)
        return frozenset(out)

    def depth(self, c: str) -> int:
        return len(self._ancestors[c])

    def branch(self, c: str) -> str:
        """The BFO top-level branch c falls under; `entity` itself has none."""
        for b in BRANCHES:
            if self.is_a(c, b):
                return b
        return B.ENTITY

    def disjoint(self, c: str, d: str) -> bool:
        """True if an asserted disjointness axiom separates c and d.

        Two classes are disjoint when some ancestor-or-self of each falls in
        one asserted disjoint group as different members.
        """
        ac, ad = self.ancestors(c, True), self.ancestors(d, True)
        for group in self._disjoint:
            gc, gd = group & ac, group & ad
            if gc and gd and (gc != gd or len(gc) > 1):
                return True
        return False

    def nearest_key(self, c: str, keys) -> Optional[str]:
        """The deepest of ``c`` and its ancestors that is in ``keys``.

        For tables keyed by class: a subclass finds its nearest keyed ancestor
        (City finds a Geospatial Region entry). The root (``bfo:entity``) only
        matches itself, so a root entry is never an inherited default. Unknown
        classes match nothing.
        """
        if not self.is_class(c):
            return None
        if c in keys:
            return c
        for a in self._ancestors_deepest_first(c):
            if a != B.ENTITY and a in keys:
                return a
        return None

    def _ancestors_deepest_first(self, c: str):
        """``c``'s ancestors, deepest first (ties by CURIE); computed once per
        class -- the hierarchy is fixed after load, and the heads resolve
        classes this way for every candidate value."""
        cache = self.__dict__.setdefault("_anc_sorted", {})
        hit = cache.get(c)
        if hit is None:
            hit = cache[c] = tuple(sorted(self._ancestors[c], key=lambda a: (-self.depth(a), a)))
        return hit

    # ---- evidence -> one class ------------------------------------------
    def resolve(self, evidence: Iterable[str],
                weights: Optional[Iterable[float]] = None) -> Optional[str]:
        """Settle a sequence of class votes on one class.

        BFO hierarchies are built on asserted single inheritance, so a
        particular gets one most-specific class. The class with the most vote
        weight wins (each vote weighs 1 unless ``weights`` are given), ties
        going to the earliest vote. Among the remaining votes, the deepest one
        that the winner subsumes refines it (votes for process and Act settle
        on Act). Votes for unknown classes are ignored.
        """
        ev = list(evidence)
        ws = [1.0] * len(ev) if weights is None else [float(w) for w in weights]
        totals: Dict[str, float] = {}
        first: Dict[str, int] = {}
        for i, (v, w) in enumerate(zip(ev, ws)):
            if v in self._classes and w > 0:
                totals[v] = totals.get(v, 0.0) + w
                first.setdefault(v, i)
        if not totals:
            return None
        winner = max(totals, key=lambda v: (totals[v], -first[v]))
        refinements = [v for v in totals if v != winner and self.is_a(v, winner)]
        if refinements:
            winner = max(refinements, key=lambda v: (self.depth(v), totals[v], -first[v]))
        return winner

    def tiers(self, classes: Iterable[str]) -> List[List[str]]:
        """Group classes by BFO branch, in BRANCHES order; `entity` goes first."""
        by: Dict[str, List[str]] = {b: [] for b in (B.ENTITY,) + BRANCHES}
        for c in classes:
            by[self.branch(c)].append(c)
        root = by.pop(B.ENTITY)
        out = []
        for b in BRANCHES:
            group = sorted(set(by[b]), key=lambda c: (self.depth(c), c))
            if b == BRANCHES[0]:
                group = sorted(set(root)) + group
            if group:
                out.append(group)
        return out


    # ---- extension -----------------------------------------------------
    def extended(self, ext: dict) -> "OntologyRegistry":
        """This registry plus an implementation's own classes (see the module
        doc). Raises ValueError, listing every problem, for an extension that
        would change a BFO/CCO answer or does not resolve."""
        if self.extension is not None:
            raise ValueError("an extended registry cannot be extended again")
        problems: List[str] = []
        if ext.get("schema") != EXTENSION_SCHEMA:
            problems.append(f"schema {ext.get('schema')!r} != {EXTENSION_SCHEMA!r}")
        name = str(ext.get("name") or "")
        if not _EXTENSION_NAME_RE.match(name):
            problems.append(f"name {name!r} must match {_EXTENSION_NAME_RE.pattern}")
        if ext.get("base_sources") != self.sources:
            problems.append("built against another BFO/CCO release than this registry's")
        own: Dict[str, dict] = ext.get("classes") or {}
        base_iris = {v["iri"] for v in self._classes.values()}
        for c, v in own.items():
            if c in self._classes:
                problems.append(f"{c}: redefines a BFO/CCO class")
            if not isinstance(v, dict) or not v.get("iri") or not v.get("label"):
                problems.append(f"{c}: needs iri and label")
                continue
            if v["iri"] in base_iris:
                problems.append(f"{c}: its IRI is a BFO/CCO class")
            for p in v.get("parents") or []:
                if p not in own and p not in self._classes:
                    problems.append(f"{c}: parent {p} is not a class")
        emittable = list(ext.get("emittable") or [])
        bad = [c for c in emittable if c not in own and c not in self._classes]
        if not emittable or bad:
            problems.append(f"emittable classes missing or unknown: {bad[:5]}")
        if problems:
            raise ValueError(f"ontology extension {name!r} rejected: " + "; ".join(problems[:10]))
        classes = dict(self._classes)
        for c, v in own.items():
            classes[c] = {"iri": v["iri"], "label": v["label"],
                          "definition": v.get("definition", ""), "parents": list(v.get("parents") or [])}
        info = {"name": name, "classes": frozenset(own), "emittable": tuple(sorted(emittable)),
                "prefixes": dict(ext.get("prefixes") or {}), "source": ext.get("source") or {}}
        return OntologyRegistry({"sources": self.sources, "classes": classes,
                                 "disjoint": [sorted(d) for d in self._disjoint]}, extension=info)


@lru_cache(maxsize=1)
def base_registry() -> OntologyRegistry:
    """The built-in BFO/CCO registry, whatever the manifest selects."""
    return OntologyRegistry(json.loads(CLASSES_PATH.read_text()))


# (artifact path, extended registry) while an implementation's ontology is
# selected; None otherwise. One assignment swaps it.
_active: Optional[Tuple[str, OntologyRegistry]] = None
_active_lock = threading.Lock()


def get_registry() -> OntologyRegistry:
    """The registry for this process: the built-in BFO/CCO registry, plus the
    selected ontology implementation's classes when it brings any."""
    active = _active
    return active[1] if active is not None else base_registry()


@lru_cache(maxsize=4)
def _extended_from(path: str) -> OntologyRegistry:
    return base_registry().extended(json.loads(Path(path).read_text()))


def use_extension(path: Optional[str]) -> Optional[str]:
    """Make ``get_registry()`` the built-in registry plus the extension
    artifact at ``path``; None returns it to the built-in registry. Returns
    the active extension's name. A bad artifact raises and changes nothing."""
    global _active
    key = str(Path(path).resolve()) if path else None
    with _active_lock:
        current = _active
        if key is None:
            if current is not None:
                logger.info("ontology.registry_extension removed=%s", current[1].extension["name"])
            _active = None
            return None
        if current is not None and current[0] == key:
            return current[1].extension["name"]
        reg = _extended_from(key)
        _active = (key, reg)
        logger.info("ontology.registry_extension active=%s classes=%d emittable=%d",
                    reg.extension["name"], len(reg.extension["classes"]), len(reg.extension["emittable"]))
        return reg.extension["name"]


def active_extension() -> Optional[str]:
    """The name of the extension ``get_registry()`` includes, or None."""
    active = _active
    return active[1].extension["name"] if active is not None else None


# Classes an ontology head emitted that the registry does not know: the
# bundler and the address builder record them here before keying the record
# bfo:entity, so a drop is visible (bounded: the first DROP_LOG_CAP classes
# are logged at warning, all are counted).
DROP_LOG_CAP = 64
_dropped_lock = threading.Lock()
_dropped_logged: set = set()
dropped_classes = {"count": 0}


def note_unknown_class(c: str, where: str) -> None:
    with _dropped_lock:
        dropped_classes["count"] += 1
        first = c not in _dropped_logged and len(_dropped_logged) < DROP_LOG_CAP
        if first:
            _dropped_logged.add(c)
    if first:
        logger.warning("ontology.unknown_class class=%s where=%s extension=%s -- keyed bfo:entity "
                       "(is the implementation's ontology active in this process?)",
                       c, where, active_extension())
